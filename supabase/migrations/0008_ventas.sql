--   crear_venta()    : venta + renglones + descuento + pago inicial + salida de stock + orden de trabajo
--   registrar_abono(): abonos posteriores (nunca mas que el saldo)
--   anular_venta()   : solo administrador; devuelve el stock y archiva la orden
--   ajustar_stock()  : solo administrador; entradas/salidas manuales con motivo
--   rx_orden()       : la hoja RX de una orden para recepcion (solo lo que lleva la hoja)

-- ============ Productos ============
alter table public.products
  add column if not exists codigo text check (codigo is null or char_length(codigo) between 1 and 40),
  add column if not exists controla_stock boolean not null default true;  -- lentes a pedido: false
create unique index if not exists products_codigo_uniq on public.products (codigo)
  where codigo is not null and deleted_at is null;

-- ============ Ventas ============
alter table public.sales
  add column if not exists numero bigint generated by default as identity,
  add column if not exists subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  add column if not exists descuento numeric(10,2) not null default 0 check (descuento >= 0),
  add column if not exists pagado numeric(10,2) not null default 0 check (pagado >= 0),
  add column if not exists estado text not null default 'activa' check (estado in ('activa', 'anulada')),
  add column if not exists observaciones text check (char_length(observaciones) <= 1000),
  add column if not exists anulada_motivo text check (char_length(anulada_motivo) <= 500),
  add column if not exists anulada_en timestamptz;
alter table public.sales add column if not exists saldo numeric(10,2) generated always as (total - pagado) stored;
create unique index if not exists sales_numero_uniq on public.sales (numero);
do $$ begin
  alter table public.sales add constraint sales_pagado_max check (pagado <= total);
exception when duplicate_object then null; end $$;

alter table public.sale_items
  add column if not exists nombre text,                                        -- foto del nombre al vender
  add column if not exists descuento numeric(10,2) not null default 0 check (descuento >= 0);

-- Abonos / pagos (solo se anade; nunca se edita ni se borra).
create table if not exists public.sale_payments (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales (id),
  monto numeric(10,2) not null check (monto > 0),
  metodo text not null check (metodo in ('efectivo', 'tarjeta', 'transferencia', 'otro')),
  nota text check (char_length(nota) <= 200),
  fecha timestamptz not null default now(),
  user_id uuid not null references public.users (id)
);
create index if not exists sale_payments_sale_idx on public.sale_payments (sale_id, fecha);
alter table public.sale_payments enable row level security;
revoke all on public.sale_payments from anon;
revoke insert, update, delete, truncate on public.sale_payments from authenticated;  -- solo via registrar_abono / crear_venta
drop policy if exists sale_payments_select on public.sale_payments;
create policy sale_payments_select on public.sale_payments for select to authenticated
  using (exists (select 1 from public.sales s where s.id = sale_id));  -- hereda la RLS de sales

-- Las ventas y los items solo se crean por crear_venta(): se cierra la insercion directa.
revoke insert, update, delete, truncate on public.sales, public.sale_items from authenticated;

-- ============ Ordenes de trabajo ============
alter table public.orders
  add column if not exists sale_id uuid references public.sales (id),
  add column if not exists notas text check (char_length(notas) <= 1000);
create index if not exists orders_sale_idx on public.orders (sale_id);

-- Auditoria de quien crea/edita ventas y abonos.
