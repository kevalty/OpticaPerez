-- ============ crear_venta ============
-- p = {
--   patient_id: uuid|null, observaciones: text|null,
--   items: [{product_id, cantidad, descuento_pct}],
--   descuento: {tipo: 'monto'|'porcentaje', valor: n} | null,
--   pago: {monto, metodo} | null,
--   orden: {fecha_entrega: 'YYYY-MM-DD'|null, notas: text|null} | null
-- }
-- Los precios salen de la tabla de productos (no del navegador). La recepcionista puede dar hasta 20 %
-- de descuento en total; mas que eso solo el administrador.
create or replace function public.crear_venta(p jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := (select auth.uid());
  es_admin boolean;
  v_patient uuid := nullif(p->>'patient_id', '')::uuid;
  x jsonb; pr public.products;
  cant integer; pct numeric; bruto numeric; desc_linea numeric;
  subtotal numeric := 0; desc_global numeric := 0; total numeric; bruto_total numeric := 0; desc_total numeric;
  v_sale uuid; v_numero bigint; v_order uuid; v_record uuid;
  pago_monto numeric := 0; pago_metodo text;
  lineas jsonb := '[]'::jsonb; l jsonb;
  max_pct constant numeric := 20;
begin
  if not public.has_role('recepcionista', 'administrador', 'otro') then
    raise exception 'No tienes permiso para registrar ventas' using errcode = '42501';
  end if;
  es_admin := public.has_role('administrador');

  if jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 then
    raise exception 'Agrega al menos un producto a la venta' using errcode = 'P0001';
  end if;
  if jsonb_array_length(p->'items') > 50 then
    raise exception 'Una venta admite hasta 50 renglones' using errcode = 'P0001';
  end if;
  if v_patient is not null and not exists (select 1 from public.patients where id = v_patient and deleted_at is null) then
    raise exception 'El paciente no existe' using errcode = 'P0001';
  end if;

  -- 1) Renglones: precio y nombre desde la base, stock bloqueado mientras dura la transaccion.
  for x in select * from jsonb_array_elements(p->'items') loop
    cant := (x->>'cantidad')::integer;
    pct := coalesce((x->>'descuento_pct')::numeric, 0);
    if cant is null or cant < 1 or cant > 999 then
      raise exception 'Cantidad no valida' using errcode = 'P0001';
    end if;
    if pct < 0 or pct > 100 then
      raise exception 'Descuento no valido' using errcode = 'P0001';
    end if;
    select * into pr from public.products
      where id = (x->>'product_id')::uuid and deleted_at is null for update;
    if not found then
      raise exception 'Un producto ya no existe en el catalogo' using errcode = 'P0001';
    end if;
    if pr.controla_stock and pr.stock < cant then
      raise exception 'Stock insuficiente de "%" (quedan %)', pr.nombre, pr.stock using errcode = 'P0001';
    end if;
    bruto := round(cant * pr.precio, 2);
    desc_linea := round(bruto * pct / 100, 2);
    subtotal := subtotal + (bruto - desc_linea);
    bruto_total := bruto_total + bruto;
    lineas := lineas || jsonb_build_object('product_id', pr.id, 'nombre', pr.nombre, 'cantidad', cant,
                'precio', pr.precio, 'descuento', desc_linea, 'controla', pr.controla_stock);
  end loop;

  -- 2) Descuento global
  if jsonb_typeof(p->'descuento') = 'object' and coalesce((p->'descuento'->>'valor')::numeric, 0) > 0 then
    if p->'descuento'->>'tipo' = 'porcentaje' then
      desc_global := round(subtotal * (p->'descuento'->>'valor')::numeric / 100, 2);
    else
      desc_global := round((p->'descuento'->>'valor')::numeric, 2);
    end if;
    if desc_global > subtotal then
      raise exception 'El descuento no puede superar el subtotal' using errcode = 'P0001';
    end if;
  end if;
  total := subtotal - desc_global;
  desc_total := bruto_total - total;
  if not es_admin and bruto_total > 0 and desc_total > round(bruto_total * max_pct / 100, 2) then
    raise exception 'Descuentos de mas de % %% necesitan autorizacion del administrador', max_pct using errcode = 'P0001';
  end if;

  -- 3) Pago inicial
  if jsonb_typeof(p->'pago') = 'object' then
    pago_monto := round(coalesce((p->'pago'->>'monto')::numeric, 0), 2);
    pago_metodo := p->'pago'->>'metodo';
    if pago_monto < 0 or pago_monto > total then
      raise exception 'El pago no puede ser mayor que el total' using errcode = 'P0001';
    end if;
    if pago_monto > 0 and pago_metodo not in ('efectivo', 'tarjeta', 'transferencia', 'otro') then
      raise exception 'Elige un metodo de pago' using errcode = 'P0001';
    end if;
  end if;

  -- 4) Venta, renglones, pago, stock
  insert into public.sales (patient_id, vendedor_id, subtotal, descuento, total, pagado, observaciones)
  values (v_patient, uid, subtotal, desc_global, total, pago_monto, left(nullif(btrim(p->>'observaciones'), ''), 1000))
  returning id, numero into v_sale, v_numero;

  for l in select * from jsonb_array_elements(lineas) loop
    insert into public.sale_items (sale_id, product_id, cantidad, precio_unitario, nombre, descuento)
    values (v_sale, (l->>'product_id')::uuid, (l->>'cantidad')::integer, (l->>'precio')::numeric, l->>'nombre', (l->>'descuento')::numeric);
    if (l->>'controla')::boolean then
      update public.products set stock = stock - (l->>'cantidad')::integer where id = (l->>'product_id')::uuid;
      insert into public.inventory_movements (product_id, tipo, cantidad, venta_id, user_id)
      values ((l->>'product_id')::uuid, 'salida', (l->>'cantidad')::integer, v_sale, uid);
    end if;
  end loop;

  if pago_monto > 0 then
    insert into public.sale_payments (sale_id, monto, metodo, user_id) values (v_sale, pago_monto, pago_metodo, uid);
  end if;

  -- 5) Orden de trabajo (necesita paciente; se liga a su ficha mas reciente para la hoja RX)
  if jsonb_typeof(p->'orden') = 'object' then
    if v_patient is null then
      raise exception 'Para generar la orden de trabajo elige un paciente' using errcode = 'P0001';
    end if;
    select id into v_record from public.medical_records
      where patient_id = v_patient and deleted_at is null order by fecha desc, created_at desc limit 1;
    insert into public.orders (patient_id, record_id, sale_id, fecha_entrega, notas, created_by)
    values (v_patient, v_record, v_sale, nullif(p->'orden'->>'fecha_entrega', '')::date,
            left(nullif(btrim(p->'orden'->>'notas'), ''), 1000), uid)
    returning id into v_order;
    insert into public.order_status_history (order_id, estado, user_id) values (v_order, 'enviado_a_hacer', uid);
  end if;

  return jsonb_build_object('sale_id', v_sale, 'numero', v_numero, 'order_id', v_order);
end $$;
revoke all on function public.crear_venta(jsonb) from public, anon;
grant execute on function public.crear_venta(jsonb) to authenticated;

-- ============ registrar_abono ============
create or replace function public.registrar_abono(p_venta uuid, p_monto numeric, p_metodo text, p_nota text default null)
returns numeric language plpgsql security definer set search_path = '' as $$
declare uid uuid := (select auth.uid()); s public.sales; v_monto numeric := round(p_monto, 2);
begin
  if not public.has_role('recepcionista', 'administrador', 'otro') then
    raise exception 'No tienes permiso para registrar pagos' using errcode = '42501';
  end if;
  select * into s from public.sales where id = p_venta and deleted_at is null for update;
  if not found or (not public.has_role('administrador') and s.vendedor_id <> uid) then
    raise exception 'Venta no encontrada' using errcode = 'P0002';
  end if;
  if s.estado = 'anulada' then
    raise exception 'La venta esta anulada' using errcode = 'P0001';
  end if;
  if v_monto is null or v_monto <= 0 then
    raise exception 'Escribe un monto mayor a cero' using errcode = 'P0001';
  end if;
  if v_monto > s.total - s.pagado then
    raise exception 'El abono supera el saldo pendiente (%)', to_char(s.total - s.pagado, 'FM999990.00') using errcode = 'P0001';
  end if;
  if p_metodo not in ('efectivo', 'tarjeta', 'transferencia', 'otro') then
    raise exception 'Elige un metodo de pago' using errcode = 'P0001';
  end if;
  insert into public.sale_payments (sale_id, monto, metodo, nota, user_id)
  values (p_venta, v_monto, p_metodo, left(nullif(btrim(p_nota), ''), 200), uid);
  update public.sales set pagado = pagado + v_monto where id = p_venta;
  return s.total - s.pagado - v_monto;
end $$;
revoke all on function public.registrar_abono(uuid, numeric, text, text) from public, anon;
grant execute on function public.registrar_abono(uuid, numeric, text, text) to authenticated;

-- ============ anular_venta (solo administrador) ============
create or replace function public.anular_venta(p_venta uuid, p_motivo text)
returns void language plpgsql security definer set search_path = '' as $$
declare uid uuid := (select auth.uid()); s public.sales; it record;
begin
  if not public.has_role('administrador') then
    raise exception 'Solo un administrador puede anular ventas' using errcode = '42501';
  end if;
  if char_length(btrim(coalesce(p_motivo, ''))) < 3 then
    raise exception 'Escribe el motivo de la anulacion' using errcode = 'P0001';
  end if;
  select * into s from public.sales where id = p_venta and deleted_at is null for update;
  if not found then raise exception 'Venta no encontrada' using errcode = 'P0002'; end if;
  if s.estado = 'anulada' then raise exception 'La venta ya esta anulada' using errcode = 'P0001'; end if;

  for it in select i.product_id, i.cantidad from public.sale_items i
            join public.products pr on pr.id = i.product_id and pr.controla_stock where i.sale_id = p_venta loop
    update public.products set stock = stock + it.cantidad where id = it.product_id;
    insert into public.inventory_movements (product_id, tipo, cantidad, venta_id, user_id)
    values (it.product_id, 'entrada', it.cantidad, p_venta, uid);
  end loop;
  update public.orders set deleted_at = now() where sale_id = p_venta and deleted_at is null;
  update public.sales set estado = 'anulada', anulada_motivo = left(btrim(p_motivo), 500), anulada_en = now() where id = p_venta;
end $$;
revoke all on function public.anular_venta(uuid, text) from public, anon;
grant execute on function public.anular_venta(uuid, text) to authenticated;

-- ============ ajustar_stock (solo administrador) ============
create or replace function public.ajustar_stock(p_producto uuid, p_delta integer)
returns integer language plpgsql security definer set search_path = '' as $$
declare uid uuid := (select auth.uid()); pr public.products;
begin
  if not public.has_role('administrador') then
    raise exception 'Solo un administrador puede ajustar el stock' using errcode = '42501';
  end if;
  if p_delta is null or p_delta = 0 or abs(p_delta) > 100000 then
    raise exception 'Cantidad no valida' using errcode = 'P0001';
  end if;
  select * into pr from public.products where id = p_producto and deleted_at is null for update;
  if not found then raise exception 'Producto no encontrado' using errcode = 'P0002'; end if;
  if pr.stock + p_delta < 0 then
    raise exception 'No hay stock suficiente para descontar (hay %)', pr.stock using errcode = 'P0001';
  end if;
  update public.products set stock = stock + p_delta where id = p_producto;
  insert into public.inventory_movements (product_id, tipo, cantidad, user_id)
  values (p_producto, case when p_delta > 0 then 'entrada' else 'salida' end::public.movement_type, abs(p_delta), uid);
  return pr.stock + p_delta;
end $$;
revoke all on function public.ajustar_stock(uuid, integer) from public, anon;
grant execute on function public.ajustar_stock(uuid, integer) to authenticated;

-- ============ rx_orden: la hoja RX de una orden, para imprimir en recepcion ============
-- Igual que certificado_recepcion: la recepcionista NO lee fichas; aqui recibe solo lo que lleva la hoja RX.
create or replace function public.rx_orden(p_orden uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare o public.orders; mr public.medical_records; res jsonb;
begin
  if not public.has_role('recepcionista', 'doctor', 'administrador', 'otro') then return null; end if;
  select * into o from public.orders where id = p_orden and deleted_at is null;
  if not found then return null; end if;
  if o.record_id is not null then
    select * into mr from public.medical_records where id = o.record_id;
  end if;
  select jsonb_build_object(
    'paciente', p.nombre, 'tipo_documento', p.tipo_documento, 'documento', p.documento,
    'telefono', p.telefono, 'email', p.email, 'direccion', p.direccion,
    'fecha', coalesce(mr.fecha, current_date),
    'recetario', mr.recetario,
    'tiene_ficha', (mr.id is not null)
  ) into res from public.patients p where p.id = o.patient_id;
  if mr.id is not null then
    insert into public.audit_log (user_id, accion, tabla, registro_id) values ((select auth.uid()), 'ver', 'medical_records', mr.id);
  end if;
  return res;
end $$;
revoke all on function public.rx_orden(uuid) from public, anon;
grant execute on function public.rx_orden(uuid) to authenticated;
